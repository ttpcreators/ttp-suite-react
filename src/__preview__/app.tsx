const q = new URLSearchParams(location.search);
localStorage.clear();
localStorage.setItem("ttp:view", q.get("view") ?? "apercu");
localStorage.setItem("ttp:tabs", JSON.stringify([q.get("view") ?? "apercu"]));
if (q.get("theme")) localStorage.setItem("ttp:theme", q.get("theme")!);
if (q.get("cstab")) localStorage.setItem("ttp:cs-tab", q.get("cstab")!);
if (q.get("csfav")) localStorage.setItem("ttp:cs-favoris", JSON.stringify(q.get("csfav")!.split(",")));
if (q.get("accent")) localStorage.setItem("ttp:accent", q.get("accent")!);
await import("../main");
export {};
